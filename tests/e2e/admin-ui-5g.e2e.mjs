// STEP 5G -- server side of the UX polish:
//   * GET /api/admin2/work/items?q=   (search only ever NARROWS the caller's authorized set)
//   * GET /api/admin2/timeline        (display names + status/priority/assignee change for the business-language timeline)
//   DATABASE_URL=<TEST db> node tests/e2e/admin-ui-5g.e2e.mjs
import assert from 'node:assert/strict'
import { db } from '../../server/lib/prisma.mjs'
import { client, startApi, createStaffUser, loginAsStaff, assignRole, makeRunner, randomUUID } from './helpers/admin2-harness.mjs'

const run = randomUUID().slice(0, 8)
const api = await startApi()
const { t, summary } = makeRunner()
const p = db()
const org = await p.organization.findFirst()
const rest = await p.platform.findUnique({ where: { code: 'sr_restaurants' } })
const ride = await p.platform.findUnique({ where: { code: 'sr_ride' } })
const tag = `5g${run}`

const owner = await createStaffUser('owner', run)
await assignRole(owner, 'OWNER', [{ kind: 'ORGANIZATION', organizationId: org.id }])
const sarah = await createStaffUser('sarah', run)
await p.user.update({ where: { id: sarah.id }, data: { displayName: 'Sarah Mansour' } })
const mk = (title, over = {}) => p.workItem.create({ data: { type: 'DOCUMENT_REVIEW', title: `${tag} ${title}`, ...over } })
const restLic = await mk('licence renewal for pizzeria', { platformId: rest.id })
const rideLic = await mk('licence renewal for ride fleet', { platformId: ride.id })
const rideSecret = await mk('zebra-secret ride item', { platformId: ride.id, type: 'SECURITY_REVIEW' })
await mk('plain restaurants item', { platformId: rest.id, type: 'PLATFORM_SETUP' })
const ownerS = await loginAsStaff(api, owner)
const restOps = await createStaffUser('rest-ops', run)
await assignRole(restOps, 'RESTAURANT_OPS', [{ kind: 'PLATFORM', platformId: rest.id }])
const opsS = await loginAsStaff(api, restOps)
const names = (items) => items.filter((x) => x.title.startsWith(tag)).map((x) => x.title.slice(tag.length + 1)).sort()
const get = (s, q, extra = '') => s.http.get(`/api/admin2/work/items?view=all&pageSize=100&q=${encodeURIComponent(q)}${extra}`)

await t('search matches title text, case-insensitively', async () => {
  const r = await get(ownerS, 'LICENCE RENEWAL')
  assert.equal(r.status, 200)
  assert.deepEqual(names(r.json.items), ['licence renewal for pizzeria', 'licence renewal for ride fleet'])
})
await t('search matches the task type label and the platform display name', async () => {
  const byType = await get(ownerS, 'security review')
  assert.ok(names(byType.json.items).includes('zebra-secret ride item'))
  assert.ok(!names(byType.json.items).includes('licence renewal for pizzeria'))
  const byPlatform = await get(ownerS, rest.displayName)
  assert.ok(names(byPlatform.json.items).includes('plain restaurants item') && !names(byPlatform.json.items).includes('zebra-secret ride item'))
})
await t('search NEVER returns records outside the caller’s authorization (platform-scoped user)', async () => {
  const noSearch = await opsS.http.get('/api/admin2/work/items?view=all&pageSize=100')
  assert.ok(!names(noSearch.json.items).includes('zebra-secret ride item'), 'baseline: ride item is invisible to restaurant ops')
  const direct = await get(opsS, 'zebra-secret')
  assert.equal(direct.status, 200); assert.deepEqual(names(direct.json.items), []); assert.equal(direct.json.total, 0)
  const shared = await get(opsS, 'licence renewal')
  assert.deepEqual(names(shared.json.items), ['licence renewal for pizzeria'], 'only the restaurants half of a shared title')
  const byRidePlatform = await get(opsS, ride.displayName)
  assert.deepEqual(names(byRidePlatform.json.items), [], 'searching another platform’s name reveals nothing')
  assert.equal(JSON.stringify(shared.json).includes('ride fleet'), false)
})
await t('search cannot be used to widen a view: the view and platform filters still apply', async () => {
  const r = await ownerS.http.get(`/api/admin2/work/items?view=mine&pageSize=100&q=${encodeURIComponent('licence')}`)
  assert.deepEqual(names(r.json.items), [], 'none of them are assigned to the owner')
  const scoped = await ownerS.http.get(`/api/admin2/work/items?view=all&pageSize=100&platformId=${ride.id}&q=${encodeURIComponent('licence renewal')}`)
  assert.deepEqual(names(scoped.json.items), ['licence renewal for ride fleet'])
})
await t('search input is validated and wildcard characters are literal', async () => {
  assert.equal((await get(ownerS, 'a')).status, 400)
  assert.equal((await get(ownerS, 'x'.repeat(81))).status, 400)
  assert.equal((await ownerS.http.get('/api/admin2/work/items?view=all&q=%20%20')).status, 200, 'blank search = no search')
  const pct = await get(ownerS, '%%'); assert.equal(pct.status, 200); assert.deepEqual(names(pct.json.items), [])
  const us = await get(ownerS, '__'); assert.deepEqual(names(us.json.items), [])
  assert.equal((await get(ownerS, `' OR 1=1 --`)).status, 200)
})
await t('pagination totals reflect the search', async () => {
  const r = await ownerS.http.get(`/api/admin2/work/items?view=all&pageSize=1&q=${encodeURIComponent(tag)}`)
  assert.equal(r.json.total, 4); assert.equal(r.json.items.length, 1); assert.equal(r.json.totalPages, 4)
})
await t('unauthenticated and role-less callers cannot search at all', async () => {
  assert.equal((await client(api.base).get('/api/admin2/work/items?q=licence')).status, 401)
  const nobody = await createStaffUser('nobody', run)
  const s = await loginAsStaff(api, nobody)
  assert.ok([401, 403].includes((await s.http.get('/api/admin2/work/items?q=licence')).status))
})

await t('timeline: actor name, assignee name and the status/priority change are provided; no emails', async () => {
  const patch = await ownerS.http.patch(`/api/admin2/work/items/${restLic.id}`, { assignedUserId: sarah.id, priority: 'HIGH' })
  assert.equal(patch.status, 200)
  const patch2 = await ownerS.http.patch(`/api/admin2/work/items/${restLic.id}`, { status: 'IN_PROGRESS' })
  assert.equal(patch2.status, 200)
  const r = await ownerS.http.get(`/api/admin2/timeline?entityType=work_item&entityId=${restLic.id}`)
  assert.equal(r.status, 200)
  const ups = r.json.events.filter((e) => e.eventType === 'updated')
  assert.equal(ups.length, 2)
  const first = ups.find((e) => e.change?.assigned)
  assert.equal(first.change.assigned.toName, 'Sarah Mansour'); assert.equal(first.change.assigned.unassigned, false)
  assert.deepEqual(first.change.priority, { from: 'NORMAL', to: 'HIGH' })
  assert.equal(first.actorName, owner.displayName ?? first.actorName); assert.ok(first.actorName)
  const second = ups.find((e) => e.change?.status)
  assert.deepEqual(second.change.status, { from: 'OPEN', to: 'IN_PROGRESS' })
  assert.ok(!r.text.includes(sarah.email) && !r.text.includes(owner.email), 'no email addresses in the timeline payload')
  assert.ok(!r.text.includes(sarah.id), 'the assignee id is resolved to a name, not echoed in `change`')
})
await t('timeline: the stored event and its raw detail are unchanged by the presentation fields', async () => {
  const row = await p.timelineEvent.findFirst({ where: { entityType: 'work_item', entityId: restLic.id, eventType: 'updated' }, orderBy: { createdAt: 'asc' } })
  assert.match(row.summary, /^Updated: /)
  assert.equal(row.detail.to.assignedUserId, sarah.id, 'raw detail still holds the id')
})
await t('timeline: unassigning is reported as such; other entity types carry no change block', async () => {
  await ownerS.http.patch(`/api/admin2/work/items/${restLic.id}`, { assignedUserId: null })
  const r = await ownerS.http.get(`/api/admin2/timeline?entityType=work_item&entityId=${restLic.id}`)
  const un = r.json.events.find((e) => e.change?.assigned?.unassigned === true)
  assert.ok(un && un.change.assigned.toName === null)
  const created = r.json.events.find((e) => e.eventType === 'created')
  assert.ok(!created || created.change === null)
})
await t('timeline: record-level authorization is unchanged (restaurant ops cannot read a ride item’s activity)', async () => {
  const denied = await opsS.http.get(`/api/admin2/timeline?entityType=work_item&entityId=${rideLic.id}`)
  assert.ok([403, 404].includes(denied.status), `got ${denied.status}`)
  const allowed = await opsS.http.get(`/api/admin2/timeline?entityType=work_item&entityId=${restLic.id}`)
  assert.equal(allowed.status, 200)
})

api.stop()
// timeline_events is append-only by design, so its rows are left in the test database.
await p.workItem.deleteMany({ where: { title: { startsWith: tag } } })
await p.$disconnect()
process.exit(summary() ? 1 : 0)
